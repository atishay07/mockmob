// Adds the `blankRuns` cases to test/unit/keycards/support/display_parity.json: what the website's own `blankRuns` (src/components/
// keycards/kinds.js, round 4: a comma, stop or closing bracket after a blank stays on the blank's line; an opening bracket or quote
// before it too) returns for the fronts of the real decks that have a blank, and for edge strings. The Key cards' display parity
// test (test/unit/keycards/display_parity_test.dart) holds the app's port (`blankRuns` in keycards_lines.dart) to every output.
//
// Run from flutter_app:  node tool/learn2_parity/blank_runs.mjs
// The web worktree is the sibling folder wt-1102-web (LEARN2_WEB overrides it). The other keys of the file are kept as they are.
// Nothing is generated by a model and nothing leaves this machine: the script reads the decks and rewrites one JSON file.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..', '..');
const web = resolve(process.env.LEARN2_WEB || resolve(app, '..', '..', 'wt-1102-web'));
const { blankRuns } = await import(pathToFileURL(resolve(web, 'src/components/keycards/kinds.js')).href);

const decks = resolve(web, 'data/keycards/decks');
const fronts = [];
for (const file of readdirSync(decks).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort()) {
  for (const card of JSON.parse(readFileSync(resolve(decks, file), 'utf8')).cards) {
    if (/_{3,}/.test(card.front || '')) fronts.push(String(card.front));
  }
}
const touches = /_{3,}[,.;:!?)\]}’”'"…%]|[([{‘“'"]_{3,}/;
// Every 4th plain blank front, and every 2nd one whose blank touches punctuation (about 800 cases from the 2,755 blank fronts).
const picked = [
  ...fronts.filter((f) => touches.test(f)).filter((_, i) => i % 2 === 0),
  ...fronts.filter((f) => !touches.test(f)).filter((_, i) => i % 4 === 0),
];
const edge = [
  '', 'No blank at all.', '____', '____, and', 'The ____, ____ and ____.', '(____)', '("____")', '“____”,', '‘____’.', 'a ____ ,b', 'a (____) b', '____...', '____…',
  'Quoted "____", then ____.', "It's ____; then ____:", 'x ____? y ____! z', 'A ____% rise', '[____]', '{____}', '____)', '((____', '____,,,', '(([“____”)),',
  '___ two only', '__ not a blank', '_____ five', '  ____  ', 'Tail ____.', '____ Head', 'Q: ____', 'A ____ B ____ C', '(____ ____)', '____,____',
  'Name the ____, the ____ and the ____, of the firm.', '("quoted", ____)', 'end with open (', '____ (see Table 2.4)', '____ — dash', '____ - hyphen',
];
const cases = [...edge, ...picked].map((front) => ({
  front,
  out: blankRuns(front).map((p) => ({ ...(p.blank ? { blank: true, n: p.n } : { text: p.text }), ...(p.lead ? { lead: p.lead } : {}), ...(p.tail ? { tail: p.tail } : {}) })),
}));

const file = resolve(app, 'test/unit/keycards/support/display_parity.json');
const data = JSON.parse(readFileSync(file, 'utf8'));
delete data.blankRuns;
data.note = 'Generated by the web kinds.js over the real decks (cards, chapterRefs, bookNames by the original script; blankRuns by tool/learn2_parity/blank_runs.mjs). Do not edit by hand.';
// The other keys keep their layout; the blankRuns cases are one per line, so a diff reads case by case.
const rest = JSON.stringify(data, null, 1).replace(/\n\}$/, '');
writeFileSync(file, `${rest},\n "blankRuns": [\n${cases.map((c) => `  ${JSON.stringify(c)}`).join(',\n')}\n ]\n}\n`);
console.log(`wrote ${file}: ${cases.length} blankRuns cases (${picked.length} from the decks)`);
