/** The matched runs as [start, end] pairs (the runs are cut from the text, so the offsets say everything). */
function hitRuns(text, query) {
  const out = [];
  let at = 0;
  for (const p of shared.hitParts(text, query)) {
    if (p.hit) out.push([at, at + p.text.length]);
    at += p.text.length;
  }
  return out;
}

const hit = [];
for (let t = 0; t < texts.length; t += 1) {
  for (let q = 0; q < queries.length; q += 1) {
    const parts = shared.hitParts(texts[t], queries[q]);
    // The parts always add up to the text: the parity test checks that too.
    if (parts.map((p) => p.text).join('') !== (texts[t] || '')) throw new Error(`hitParts changed the text of ${t} for query ${q}`);
    hit.push({ t, q, runs: hitRuns(texts[t], queries[q]), n: parts.length });
  }
}

