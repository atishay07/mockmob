/** Every output of the cover words for one cover, over every length and every flag. */
function describe(c) {
  const media = model.mediaOf(c, 10);
  const out = {
    refLine: model.refLineOf(c) ?? null,
    lead: { history: model.leadLine(c, { history: true }), noHistory: model.leadLine(c, { history: false }) },
    student: { history: model.studentLineOf(c, { history: true }) ?? null, noHistory: model.studentLineOf(c, { history: false }) ?? null },
    opensQuestions: { open: model.opensQuestions(c, { freeDone: false }), done: model.opensQuestions(c, { freeDone: true }) },
    tier: media.kind === 'card' ? model.hookTier(media.text) : null,
    byLength: {},
  };
  for (const m of MINUTES) {
    const n = model.countsOf(c, m);
    out.byLength[m] = {
      counts: { cards: Number(n.cards) || 0, questions: Number(n.questions) || 0, minutes: Number(n.minutes) || 0, capped: flag(n.capped) },
      mix: { pro: model.mixLineOf(c, m), free: model.mixLineOf(c, m, { free: true }) },
      key: { open: model.keyLabelOf(c, m), done: model.keyLabelOf(c, m, { freeDone: true }) },
      media: model.mediaOf(c, m),
    };
  }
  return out;
}

