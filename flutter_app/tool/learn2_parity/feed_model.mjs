// ---------------------------------------------------------------- the states a student leaves

const right = { answer: { choice: 'A', res: { correct: true, key: 'A', choice: 'A' } } };
const wrong = { answer: { choice: 'B', res: { correct: false, key: 'A', choice: 'B' } } };
const pending = { answer: { choice: 'A', pending: true } };

/** Deterministic states over a list: none; some (cards seen, one kept, answers right and wrong, one pending, one left out); all done. */
function statesFor(items) {
  const some = {};
  const all = {};
  let cards = 0;
  let questions = 0;
  items.forEach((it, i) => {
    if (it.type === 'card') {
      cards += 1;
      if (cards <= 4) some[it.id] = { seen: true, ...(cards === 2 ? { kept: true } : {}), ...(cards === 3 ? { turned: true, seenBack: true } : {}) };
      if (cards === 5) some[it.id] = { kept: true };
      all[it.id] = { seen: true, seenBack: true, ...(i % 2 ? { kept: true } : {}) };
    } else {
      questions += 1;
      const pick = [right, wrong, pending, { skipped: 'This question changed a moment ago, so it is left out.' }, right][(questions - 1) % 5];
      some[it.id] = JSON.parse(JSON.stringify(pick));
      all[it.id] = JSON.parse(JSON.stringify(questions % 3 === 0 ? wrong : right));
    }
  });
  return { none: {}, some, all };
}

const states = {};
