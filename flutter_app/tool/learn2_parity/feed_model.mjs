const ids = (list) => list.map((x) => x.id);
const splice = [];
function spliceCase(listName, list, answeredId, reinsert, resumed) {
  const out = model.spliceReinsert(list, { answeredId, reinsert, resumed });
  // The input is the named list itself, or (ids) that list with the re-insert's copy already in it.
  const own = list === lists[listName].items;
  // The re-insert's item is written as a reference: the list's item `ref` under the id `id` (a copy, as the server makes).
  const { item, ...rest } = reinsert;
  const said = item ? { ...rest, item: { ref: item.ref || item.id, id: item.id } } : rest;
  splice.push({ list: listName, ...(own ? {} : { ids: ids(list) }), answeredId, reinsert: said, resumed, out: out === list ? null : ids(out), same: out === list });
}
for (const [name, l] of Object.entries(lists)) {
  const items = l.items;
  const qs = items.map((x, i) => [x, i]).filter(([x]) => x.type === 'question').slice(0, 2);
  const firstCard = items.find((x) => x.type === 'card');
  for (const [qi, at] of qs) {
    const copy = firstCard ? { ...JSON.parse(JSON.stringify(firstCard)), id: `${qi.id}-r1`, stage: 'again', ref: firstCard.id } : null;
    if (copy) {
      for (const where of [at + 3, 0, -5, items.length + 10, 2]) spliceCase(name, items, qi.id, { itemId: copy.id, at: where, item: copy }, false);
      spliceCase(name, items, qi.id, { itemId: copy.id, item: copy }, false);
      spliceCase(name, items, qi.id, { itemId: copy.id, at: 99, item: copy }, true);
      spliceCase(name, items, qi.id, { itemId: copy.id, at: null, item: copy }, false);
      spliceCase(name, items, qi.id, { itemId: copy.id, at: '4', item: copy }, false);
      // An id already in the list is never added twice.
      spliceCase(name, items, qi.id, { itemId: firstCard.id, at: at + 3, item: JSON.parse(JSON.stringify(firstCard)) }, false);
      spliceCase(name, [...items.slice(0, at + 1), copy, ...items.slice(at + 1)], qi.id, { itemId: copy.id, at: at + 3, item: copy }, false);
    }
    // A moved card: from ahead to its place; a closer one stays; one not in the list changes nothing.
    const ahead = items.map((x, i) => [x, i]).filter(([x, i]) => x.type === 'card' && i > at + 3).slice(-1)[0];
    if (ahead) {
      spliceCase(name, items, qi.id, { itemId: ahead[0].id, at: at + 3, moved: true, item: JSON.parse(JSON.stringify(ahead[0])) }, false);
      spliceCase(name, items, qi.id, { itemId: ahead[0].id, at: at + 3, moved: true }, false);
      spliceCase(name, items, qi.id, { itemId: ahead[0].id, at: 40, moved: true }, false);
      spliceCase(name, items, qi.id, { itemId: ahead[0].id, at: 1, moved: true }, true);
    }
    const closer = items.map((x, i) => [x, i]).find(([x, i]) => x.type === 'card' && i > at && i <= at + 2);
    if (closer) spliceCase(name, items, qi.id, { itemId: closer[0].id, at: at + 3, moved: true }, false);
    spliceCase(name, items, qi.id, { itemId: 'not-in-the-list', at: at + 3, moved: true }, false);
    spliceCase(name, items, qi.id, { itemId: 'no-item', at: at + 3 }, false);
  }
  if (firstCard) spliceCase(name, items, 'not-there', { itemId: 'x-r9', at: 5, item: { ...JSON.parse(JSON.stringify(firstCard)), id: 'x-r9', ref: firstCard.id } }, false);
}

