const SORT_IDS = ['book', 'due', 'needs', 'marks'];

/** Everything the app's roadmap asks of the model for one set of parts, as the web answers it (the parts the page draws are the playable ones). */
function mapView(allParts) {
  const parts = model.playableParts(allParts);
  const flat = model.flatRows(parts);
  const rowOf = ({ row }) => {
    const road = model.roadmapRow(row);
    return {
      key: row.key,
      cardsText: model.cardsText(row),
      nothingToPlay: model.nothingToPlay(row),
      metaLine: model.metaLine(row),
      marksText: model.marksText(row),
      title: model.displayTitle(row.title),
      verdictText: model.verdictText(row) ?? null,
      road: { line: road.line, share: road.share, seen: road.seen, verdict: road.verdict ?? null, total: road.total },
    };
  };
  return {
    playable: parts.map((part) => ({ id: part.id, hasOption: Boolean(part.option), units: part.units.map((u) => ({ title: u.title, optionId: u.optionId ?? null, chapters: u.chapters.map((c) => c.key) })) })),
    chapterTotal: model.chapterTotal(parts),
    hasMarks: model.hasMarks(parts),
    sortsFor: model.sortsFor(parts).map((s) => s.id),
    sorts: Object.fromEntries(SORT_IDS.map((id) => [id, model.sortRows(parts, id).map((f) => f.row.key)])),
    marksOrder: model.marksOrder(parts).map((f) => f.row.key),
    flat: flat.map((f) => ({ key: f.row.key, part: f.part.id, unit: f.unit.title, at: f.at })),
    freeEach: { pro: model.freeEach(flat.map((f) => f.row), true) ?? null, free: model.freeEach(flat.map((f) => f.row), false) ?? null },
    rows: flat.map(rowOf),
    parts: parts.map((part, at) => {
      const ids = (part.option?.choices || []).map((c) => c.id);
      return {
        id: part.id,
        signature: model.unitsSignature(part.units),
        optionLine: part.option ? model.optionLine(part, at) : null,
        implied: part.option ? [{ choice: null, out: model.impliedOptionLine(part, null) ?? null }, ...ids.map((id) => ({ choice: id, out: model.impliedOptionLine(part, id) ?? null }))] : [],
        units: part.units.map((unit) => ({ title: unit.title, optionId: unit.optionId ?? null, heading: model.unitHeading(unit) ?? null })),
        effective: [
          { local: null, out: model.effectiveChoice(part, {}) ?? null },
          ...ids.map((id) => ({ local: id, out: model.effectiveChoice(part, { [part.id]: id }) ?? null })),
        ],
        // The units shown for no choice, for each choice, and for a choice no unit carries.
        shown: Object.fromEntries([['', null], ...ids.map((id) => [id, id]), ['none-such', 'none-such']].map(([k, choice]) => [k, model.unitsSignature(model.shownOptionUnits(part.units, choice))])),
        optionCounts: Object.fromEntries(ids.map((id) => [id, model.optionChapterCount(part.units, id)])),
      };
    }),
  };
}

