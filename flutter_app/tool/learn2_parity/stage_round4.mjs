// The stage's round 4 parity cases, called by stage_text.mjs: what the website's own pure modules return for
//   sciText.mjs      science notation, over every Chemistry card's words and the strings the web's tests hold
//   endModel.mjs     the one end screen's headline, numbers, bar, mini fronts, checkpoint, stop line and Free's rows
//   pagerModel.mjs   verdictScrollTop and optionsBelow (the two rules round 4 added)
// The Dart ports (sci_text.dart, stage_end_model.dart, pager_model.dart) are held to every output by
// test/unit/learn2/stage/stage_text_parity_test.dart. Nothing is generated by a model; the script only reads.
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const grid = (...lists) => lists.reduce((acc, list) => acc.flatMap((a) => list.map((x) => [...a, x])), [[]]);

export async function round4({ load, web, app, cards }) {
  const sci = await load('src/components/learn2/stage/sciText.mjs');
  const endModel = await load('src/components/learn2/stage/endModel.mjs');
  const pagerModel = await load('src/components/learn2/stage/pagerModel.mjs');

  // ------------------------------------------------------------ science notation
  const chemistry = JSON.parse(readFileSync(resolve(web, 'data/keycards/decks/chemistry.json'), 'utf8')).cards;
  const sciEdge = [
    '', 'SO42− and NH4+ ions', 'Cu2+, Fe2+, Fe3+, Zn2+, Ag+, Na+, K+, Ca2+, Mg2+, Al3+', 'OH−, NO3−, CO32−, PO43−, HCO3−, Cl−, H3O+', 'Cl- and SO42- ions',
    'SO42−', 'NH4+', 'CH3OH, (CH3)2NH, PbO2, H2SO4, C6H5OH', '2H2O and CuSO4·5H2O', '(CH3)2NH', '[A]0 and [R]0', 'The half-life t1/2 is constant.',
    'Table 2.4', 'Unit 4', 'p. 52', 'step 1', '373 K', 'NCERT, Chemistry Part 1, Ch 2, p. 48', 'SN1 and SN2, E1, E2', 'Vitamin B12', 'Class 12', 'pH 7',
    'I- and F-', 'Part I-A', 'O2 and O2−', '[Co(NH3)6]3+ is octahedral', '[PtCl4]2– is square planar', 'how NO2– can coordinate', 'configuration 3d8.',
    'from d4 to d3', '1s2 2s2 2p6', 'a Br–Br bond and the C–Cl bond', 'pp. 89–117, Table 2.4, step 1, Unit 4, 373 K', 'for d4 (Cr2+, Mn3+), d6 (Fe2+, Co3+)',
    'the NO2– and SCN– ions', '(CH3)2NH and (C2H5)2NH', 'Mn3+ and Co3+', 'Fe(OH)3 and Al(OH)3', 'K4[Fe(CN)6]', 'H2O, CO2, NH3', 'x1/2', 'at t1/2 the rate', '[X]00',
    '[A]0 is [A]0.', '1 mol L-1 s-1', 'Na2CO3 + 2HCl', '2KMnO4', 'MnO4− to Mn2+', 'Cr2O72−', 'H+ and OH−', 'A- B+', 'Ca(OH)2', '(NH4)2SO4', 'C2H5OH–H2O',
  ];
  const inputs = [];
  const seen = new Set();
  const add = (t) => {
    const x = String(t ?? '');
    if (!seen.has(x)) { seen.add(x); inputs.push(x); }
  };
  sciEdge.forEach(add);
  for (const c of chemistry) {
    add(c.front);
    String(c.front || '').split(/_{3,}/).forEach(add);
    add(c.back);
    String(c.back || '').split('\n').forEach(add);
  }
  // A text that draws plain carries no segments (null); the rest carry [kind, text] pairs.
  // Only a text that could draw notation (a digit, a sign or a dash) is a case; a sentence of words is plain by construction.
  const risky = inputs.filter((t) => t === '' || /[0-9+−–-]/.test(t));
  const sciCases = risky.map((t) => {
    const segs = sci.sciText(t);
    return { text: t, segments: segs.length === 0 || (segs.length === 1 && segs[0].kind === 'plain') ? null : segs.map((p) => [p.kind, p.text]) };
  });
  const isChemistry = [
    [{ subject: 'chemistry' }, null], [null, 'chemistry.solutions'], [null, 'accountancy.partnership-fundamentals'], [{}, null], [{ chapterKey: 'chemistry.x' }, null],
    [{ subject: 'physics', chapterKey: 'chemistry.x' }, 'chemistry.y'], [{ subject: 'Chemistry' }, null], [null, null], [null, 'CHEMISTRY'],
  ].map(([card, chapterKey]) => ({ card, chapterKey, out: sci.isChemistry(card, chapterKey) }));

  // ------------------------------------------------------------ the end model
  const headlines = grid([0, 1, 5, 12, 20, 22], [0, 6, 12, 20], [undefined, 0, 1, 2, 12.4, 40], [false, true]).map(([reached, of, minutes, stopped]) => ({
    reached, of, minutes: minutes ?? null, stopped, out: endModel.endHeadline({ reached, of, minutes, stopped }),
  }));
  const groupSets = [
    undefined, [], [{ label: 'back on Wed', count: 14 }], [{ label: 'back on Wed', count: 0 }, { label: 'back on Fri', count: 2 }], [{ label: 'back tomorrow', count: 3 }],
    [{ label: 'back on Wed', count: 1 }, { label: 'back in 20 days', count: 1 }], [{ label: '', count: 4 }], [{ count: 4 }], [{ label: 'back on  Sat ', count: '3' }],
    [null, { label: 'back on Mon', count: 2 }],
  ];
  const reviseLabels = groupSets.map((groups) => ({ groups: groups ?? null, out: endModel.reviseLabel(groups) }));
  const numbers = grid([0, 3, 14], ['in Revise', 'in Revise, back Wed'], [0, 1, 2], [0, 1, 2], [null, 0, 2], [0, 1, 2]).map(([revise, reviseText, answered, right, mistakes, fixed]) => ({
    revise, reviseText, answered, right, mistakes, fixed, out: endModel.endNumbers({ revise, reviseText, answered, right, mistakes, fixed }),
  }));
  const progressInputs = [
    undefined, null, {}, { of: 0, seen: 0 }, { of: 45, seen: 0 }, { of: 45, seen: 20, before: 11 }, { of: 45, seen: 20 }, { of: 45, seen: 60, before: 50 }, { of: 10, seen: 5, before: 9 },
    { of: 52, seen: 5, before: 0, open: 5 }, { of: 52, seen: 4, before: 0, open: 5 }, { of: 52, seen: 11, open: 5 }, { of: 5, seen: 5, open: 5 }, { of: 52, seen: 52, open: 52 }, { of: 52, seen: 6, open: 0 },
    { of: 52, seen: 6, open: null }, { of: 52, seen: 6, open: '' }, { of: 52, seen: 5, open: '5' }, { of: 52, seen: 8, before: 3, open: 5 }, { of: '45', seen: '20' },
  ];
  const progress = progressInputs.map((input) => ({ input: input ?? null, out: endModel.endProgress(input) ?? null }));
  const miniInputs = [
    ...cards.map((c) => c.front), ...chemistry.slice(0, 200).map((c) => c.front),
    '', 'Short', 'x'.repeat(54), 'x'.repeat(55), 'word '.repeat(20), 'Name the 6 essential features of a partnership', 'What is the ____ ratio of a firm, ____ and ____?',
    'Supercalifragilisticexpialidocious-and-more-and-more-and-more-and-more-and-more', 'A very long first word then others: Pneumonoultramicroscopicsilicovolcanoconiosis x y z',
    'Cut here, then more words follow to go past the limit of fifty-four chars.', 'Cut at a dash - then more words follow to go past the limit of fifty-four.', 'a b c d e f g h i j k l m n o p q r s t u v w x y z a b c',
    '  spaced   out   front  ', 'End with colon: and more words follow so the cut lands near a colon; yes',
  ];
  const minis = miniInputs.flatMap((t) => [54, 72].map((max) => ({ text: t, max, out: endModel.miniFront(t, max) })));
  const pileSizes = [...cards.map((c) => c.front), '', 'short words only', 'Revaluation of assets and liabilities', 'Super-long-hyphenated-word here', 'Ünïcödé wörds', '12345678901 x']
    .map((t) => ({ text: t, out: endModel.pileFrontSize(t) }));
  const checkpoints = grid([0, 1, 3], [0, 1, 2], [0, 6], [0, 3], [0, 8], [0, 16], [null, 'About 6 min left']).map(([answered, right, seenCount, kept, done, of, left]) => ({
    answered, right, seen: seenCount, kept, done, of, left, out: endModel.checkpointLines({ answered, right, seen: seenCount, kept }, { done, of, left }),
  }));
  const stopLines = grid([0, 1, 5, 20], [0, 1, 20, 21]).map(([done, of]) => ({ done, of, out: endModel.stopSheetLine(done, of) }));
  // R5 LK45 fix 2: the one count of "done", the place of the last item the server holds an event for.
  const heldPatterns = [[], [false], [true], [false, false, false], [true, false, false], [false, true, false, false], [true, true, true, true], [true, false, true, false, false], [false, false, false, true]];
  const reached = grid(heldPatterns, [0, 2, 9]).map(([held, base]) => ({ held, base, out: endModel.reachedPlace(held, (h) => h, base) }));
  const dueText = (n, m) => `Revise ${n} due card${n === 1 ? '' : 's'} · ${m} min`;
  const freeBodies = [
    {},
    { resume: null, options: [] },
    { resume: { id: 'r1', kind: 'feed', chapterKey: 'accountancy.admission-of-partner', done: 3, of: 12, minutesLeft: 6, title: 'Admission of a Partner' }, options: [] },
    { resume: { id: 'r1', done: 12, of: 12, minutesLeft: 0 }, options: [] },
    { resume: { id: 'r1', done: 3, of: 12 }, options: [{ label: 'Revise 8 due cards', run: { kind: 'cards', chapterKey: 'a.b', cardIds: ['1', '2', '3', '4', '5', '6', '7', '8'], minutes: 2 } }] },
    { resume: null, options: [{ label: 'Revise 8 due cards', run: { kind: 'cards', chapterKey: 'a.b', cardIds: [], minutes: 1.4 } }] },
    { resume: null, options: [{ label: 'Revise cards', run: { kind: 'cards', chapterKey: 'a.b', cardIds: [] } }, { label: 'Explore', href: '/explore', go: 'explore' }] },
    { resume: { id: 'r2', done: 0, of: 5, minutesLeft: 2.2 }, options: [{ label: dueText(3, 1), run: { kind: 'cards', cardIds: ['a', 'b', 'c'], minutes: 0.4 } }, { label: 'Answer single questions', href: '/explore', go: 'explore' }] },
    { resume: { id: 'r3', done: 'x', of: 5 }, options: [{ label: 'Quick recap', run: { kind: 'recap' } }] },
    { resume: { id: 'r4', done: null, of: 5, minutesLeft: null }, options: [] },
  ];
  const recorded = resolve(app, 'test/fixtures/learn2/error_402_free_session_used.json');
  try {
    const body = JSON.parse(readFileSync(recorded, 'utf8'));
    freeBodies.push(body.body ?? body.data ?? body);
  } catch { /* not recorded here */ }
  const freeRows = freeBodies.map((data) => ({ data, out: endModel.freeUsedRows(data) }));

  // ------------------------------------------------------------ the pager's new rules
  const verdicts = grid([0, 50], [70], [770], [null, 90, 170, 300, 500], [600, 700, 900], [800, 900, 1100, 1300], [24, 0]).map(([scrollTop, boxTop, boxBottom, headTop, targetTop, targetBottom, fade]) => {
    const target = { top: targetTop, bottom: Math.max(targetBottom, targetTop + 1) };
    const input = { box: { top: boxTop, bottom: boxBottom, scrollTop }, head: headTop === null ? null : { top: headTop }, target, fade };
    return { scrollTop, boxTop, boxBottom, headTop, targetTop, targetBottom: target.bottom, fade, out: pagerModel.verdictScrollTop(input) ?? null };
  });
  for (const input of [
    { box: { top: 0, bottom: 800, scrollTop: 0 }, head: { top: 40 }, target: { top: 300, bottom: 420 } },
    { box: { top: 0, bottom: 800, scrollTop: 50 }, head: { top: 500 }, target: { top: 900, bottom: 1000 } },
    { box: { top: 70, bottom: 770, scrollTop: 0 }, head: { top: 300 }, target: { top: 700, bottom: 1100 } },
    { box: { top: 70, bottom: 770, scrollTop: 0 }, head: { top: 170 }, target: { top: 700, bottom: 1100 } },
  ]) {
    verdicts.push({ scrollTop: input.box.scrollTop, boxTop: input.box.top, boxBottom: input.box.bottom, headTop: input.head.top, targetTop: input.target.top, targetBottom: input.target.bottom, fade: 24, out: pagerModel.verdictScrollTop(input) ?? null });
  }
  const number = (x) => (Number.isFinite(x) ? x : String(x));
  const below = grid([400, 732, 733, 740, 800, Number.NaN, Infinity], [760, 700, Number.NaN]).map(([optionTop, edge]) => ({ optionTop: number(optionTop), edge: number(edge), out: pagerModel.optionsBelow({ optionTop, edge }) }));

  return {
    sci: { cases: sciCases, isChemistry },
    end: { headlines, reviseLabels, numbers, progress, minis, pileSizes, checkpoints, stopLines, reached, freeRows },
    pager: { verdicts, below },
  };
}
