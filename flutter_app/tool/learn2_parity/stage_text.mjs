// Writes test/fixtures/learn2/parity/stage_text.json: what the website's own stage text rules return
// (src/components/learn2/stage/stageText.mjs and stemParts in src/components/learn2/run/runMath.js) for the
// Learn preview's 53 real questions, the Key cards of test/unit/keycards/support/display_parity.json and a set of
// edge strings, and (round 4, stage_round4.mjs) the stage's other pure modules: sciText.mjs, endModel.mjs and the two new rules of
// pagerModel.mjs. test/unit/learn2/stage/stage_text_parity_test.dart holds the app's ports (stage_text.dart, sci_text.dart,
// stage_end_model.dart, pager_model.dart) to every output exactly.
//
// Run from flutter_app:  node tool/learn2_parity/stage_text.mjs
// The web worktree is the sibling folder wt-1102-web (LEARN2_WEB overrides it). Nothing is generated by a
// model and nothing leaves this machine: the script only reads the two worktrees and writes one JSON file.
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { round4 } from './stage_round4.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..', '..');
const web = resolve(process.env.LEARN2_WEB || resolve(app, '..', '..', 'wt-1102-web'));
const load = (rel) => import(pathToFileURL(resolve(web, rel)).href);

const text = await load('src/components/learn2/stage/stageText.mjs');
const { stemParts } = await load('src/components/learn2/run/runMath.js');
// The options as the server serves them (a stored string list becomes { key: 'A', text }), so the app sees what the
// web's own Options sees.
const { servedOptions } = await load('src/lib/server/learn.js');

let commit = process.env.LEARN2_WEB_COMMIT || 'unknown';
try { commit = execSync('git rev-parse --short=9 HEAD', { cwd: web }).toString().trim(); } catch { /* not a git folder */ }

const questions = JSON.parse(readFileSync(resolve(web, 'data/fixtures/learn-preview-questions.json'), 'utf8')).questions;
const cards = JSON.parse(readFileSync(resolve(app, 'test/unit/keycards/support/display_parity.json'), 'utf8')).cards.map((c) => c.card);

// Stems that are not in the fixtures: the shapes the rules must refuse or take, and whitespace the port must read
// as the web does.
const edgeStems = [
  '',
  'What is goodwill?',
  'Assertion (A): Goodwill is an asset. Reason (R): It can be sold.',
  'assertion: lower case still counts.\nreason: and spans\nlines.',
  'Assertion: no reason here at all.',
  'Match each situation in List-I with its treatment in List-II. List-I (A) Paid privately. (B) Through the firm. List-II (I) No entry. (II) Bank A/c Dr. (III) Nil. Choose the correct answer from the options given below:',
  'Match List I with List II: List I: (A) One (B) Two List II: (1) First (2) Second Select the right code.',
  'Match List-I with List-II. List-I (A) Only one item. List-II (I) One. (II) Two.',
  'Match List-I with List-II. List-I (A) a (B) b List-II (P) p (Q) q (R) r',
  'List-II (I) before (II) list one List-I (A) x (B) y',
  'Read the following statements. Statement I: Goodwill is an asset. Statement II: It can be sold. Statement III: It is tangible. Choose the correct option.',
  'Which of the following is right? Statement 1: a. Statement 2: b.',
  'Statement I: only one statement here.',
  'Consider: Statement I - first. Statement II – second? Which one holds',
  'Statement I: x. Statement II: Choose',
  'Statement IV: four. Statement V: five.',
  'Arrange in order: (A) Record goodwill (B) Raise capital (C) Credit partners. Choose the correct sequence.',
  'Steps: (i) one (ii) two (iii) three',
  'Steps: (1) one (2) two (3) three (4) four; Pick the order.',
  'Only two: (A) one (B) two',
  'Out of order: (A) one (C) three (B) two',
  'Used again: (A) one (B) two (C) three, then (A) again',
  '  Spaces and\ttabs\n\nand  breaks  ',
  'x'.repeat(200),
  'x'.repeat(201),
];

const stems = [
  ...questions.map((q) => ({ id: q.id, stem: q.body || '' })),
  ...edgeStems.map((stem, i) => ({ id: `edge-${i}`, stem })),
].map(({ id, stem }) => ({
  id,
  stem,
  assertionReason: text.assertionReason(stem),
  matchLists: text.matchLists(stem),
  statementList: text.statementList(stem),
  stemParts: stemParts(stem),
  stemSize: text.stemSize(stem),
}));

const edgeOptions = [
  [{ key: 'A', text: 'A. Nil' }, { key: 'B', text: 'B. Rs 100' }],
  [{ key: 'A', text: '(A) Nil' }, { key: 'B', text: '(B) Rs 100' }],
  [{ key: 'A', text: 'A reduction in capital' }, { key: 'B', text: 'Both' }],
  [{ key: 'A', text: 'A) one' }, { key: 'B', text: 'B: two' }, { key: 'C', text: 'C- three' }],
  [{ key: 'A', text: 'A' }, { key: 'B', text: 'B' }],
  [{ key: 'A', text: '  A.  padded  ' }, { key: 'B', text: 'B.\tTab' }],
  [{ key: 'a', text: 'a. lower' }, { key: 'b', text: 'b. keys' }],
  [{ key: '1', text: '1. one' }, { key: '2', text: '2. two' }],
  [{ key: 'A', text: 'A. One' }, { key: 'B', text: 'Two without its letter' }],
  [{ key: 'A', text: 'Rs 25,200, Rs 16,800 and Nil' }, { key: 'B', text: 'Nil' }],
  [{ key: 'A', text: 'a'.repeat(29) }, { key: 'B', text: 'b' }],
  [{ key: 'A', text: 'One' }],
  [],
];
const options = [
  ...questions.map((q) => servedOptions(q.options)),
  ...edgeOptions,
].map((list) => {
  const texts = text.optionTexts(list);
  return { options: list.map((o) => ({ key: String(o.key), text: String(o.text ?? '') })), optionTexts: texts, twoColumns: text.twoColumns(texts) };
});

const edgeFronts = ['', 'What is goodwill?', 'x'.repeat(60), 'x'.repeat(61), 'x'.repeat(120), 'x'.repeat(121), 'The ____ ratio', 'A  ____  and\n____ gap', '__ two only', '  spaced   front  '];
const fronts = [...cards.map((c) => c.front), ...edgeFronts].map((t) => ({ text: t, frontSize: text.frontSize(t), speakable: text.speakable(t) }));

const edgeBacks = ['', 'x'.repeat(110), 'x'.repeat(111), 'x'.repeat(200), 'x'.repeat(201), 'x'.repeat(320), 'x'.repeat(321), `${'x'.repeat(98)}\n`, `${'x'.repeat(99)}\n`, 'a\nb\nc'];
const backs = [...cards.map((c) => c.back), ...edgeBacks].map((t) => ({ text: t, backSize: text.backSize(t) }));

const doneInputs = [
  { reached: 21, of: 21, minutes: 9 }, { reached: 21, of: 21 }, { reached: 8, of: 21, minutes: 4 }, { reached: 0, of: 0 },
  { reached: 22, of: 21, minutes: 0.4 }, { reached: 21, of: 21, minutes: 2.5 }, { reached: -3, of: 10 }, { reached: 10, of: 10, minutes: 0 },
  { reached: 10, of: 10, minutes: -2 }, { reached: 3, of: 3, minutes: 1.49 },
];
const doneLines = doneInputs.map((input) => ({ input, out: text.doneLine(input) }));

const seconds = [0, -5, 1, 30, 54, 54.5, 55, 60, 89, 90, 300, 330, 600, 2400, 12.5];
const timeLeft = seconds.map((s) => ({ seconds: s, out: text.timeLeft(s) }));

const refInputs = [
  { ref: 'Ch 4', partTitle: 'Accountancy Part 1' }, {}, { ref: 'Ch 2' }, { partTitle: 'Part 2' },
  { ref: 'Ch 1', partTitle: 'Same', title: 'Same' }, { ref: '', partTitle: '' }, { ref: 'Ch 3', partTitle: 'Accountancy Part 2', title: 'Other' },
];
const chapterRefs = refInputs.map((input) => ({ input, out: text.chapterRef(input) }));

const plurals = [[0, 'card'], [1, 'card'], [2, 'card'], [1, 'mistake', 'mistakes'], [3, 'child', 'children']].map(([n, one, many]) => ({ n, one, many: many ?? null, out: many ? text.plural(n, one, many) : text.plural(n, one) }));

const extra = await round4({ load, web, app, cards });

const out = {
  web: `${process.env.LEARN2_WEB_NAME || 'wt-1102-web'} ${commit}`,
  note: 'Written by tool/learn2_parity/stage_text.mjs from the web\'s own stageText.mjs and runMath.js stemParts. Do not edit by hand.',
  counts: { questions: questions.length, cards: cards.length, stems: stems.length, options: options.length },
  stems,
  options,
  fronts,
  backs,
  doneLines,
  timeLeft,
  chapterRefs,
  plurals,
  ...extra,
};

const file = resolve(app, 'test/fixtures/learn2/parity/stage_text.json');
mkdirSync(dirname(file), { recursive: true });
// One case per line: the round 4 sections hold thousands of cases, and a diff should read case by case.
const lines = (v) => {
  if (Array.isArray(v)) return v.length ? `[\n${v.map((x) => JSON.stringify(x)).join(',\n')}\n]` : '[]';
  if (v && typeof v === 'object') return `{\n${Object.entries(v).map(([k, x]) => `${JSON.stringify(k)}: ${lines(x)}`).join(',\n')}\n}`;
  return JSON.stringify(v);
};
writeFileSync(file, `${lines(out)}\n`);
console.log(`wrote ${file}: ${stems.length} stems, ${options.length} option sets, ${fronts.length} fronts, ${backs.length} backs, ${extra.sci.cases.length} science texts, ${extra.end.numbers.length} end numbers, ${extra.pager.verdicts.length} verdict scrolls`);
