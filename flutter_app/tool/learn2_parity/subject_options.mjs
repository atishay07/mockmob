// Writes test/fixtures/learn2/parity/subject_options.json: the website's subject options (data/cuet_syllabus.js SUBJECT_OPTIONS:
// Mathematics and Computer Science B1/B2, Accountancy AFS/CAS, owner LK94) and what its normalizeOption and defaultOption return
// for a set of inputs. test/unit/learn2/data/subject_options_parity_test.dart holds the app's one source of them
// (lib/core/domain/subject_options.dart) to every output exactly: ids, labels, the "Section" or "Part" word and the default.
//
// Run from flutter_app:  node tool/learn2_parity/subject_options.mjs
// The web worktree is the sibling folder wt-1102-web (origin/main; LEARN2_WEB overrides it). Nothing is generated by a model and
// nothing leaves this machine: the script only reads the web's syllabus module and writes one JSON file.
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..', '..');
const web = resolve(process.env.LEARN2_WEB || resolve(app, '..', '..', 'wt-1102-web'));
const syllabus = await import(pathToFileURL(resolve(web, 'data/cuet_syllabus.js')).href);

let commit = process.env.LEARN2_WEB_COMMIT || 'unknown';
try { commit = execSync('git rev-parse --short=9 HEAD', { cwd: web }).toString().trim(); } catch { /* not a git folder */ }

const subjects = ['mathematics', 'computer_science', 'accountancy', 'economics', 'english', ' accountancy ', 'Accountancy', '', null];
const options = ['B1', 'B2', 'b2', ' B1 ', 'AFS', 'cas', 'CAS', 'A1', 'A', 'B3', '', null];

const out = {
  web: `${process.env.LEARN2_WEB_NAME || 'wt-1102-web'} ${commit}`,
  note: "Written by tool/learn2_parity/subject_options.mjs from the web's own data/cuet_syllabus.js. Do not edit by hand.",
  options: syllabus.SUBJECT_OPTIONS,
  defaults: subjects.map((subject) => ({ subject, out: syllabus.defaultOption(subject) })),
  normalize: subjects.flatMap((subject) => options.map((option) => ({ subject, option, out: syllabus.normalizeOption(subject, option) }))),
};

const file = resolve(app, 'test/fixtures/learn2/parity/subject_options.json');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, `${JSON.stringify(out, null, 1)}\n`);
console.log(`wrote ${file}: ${Object.keys(out.options).length} subjects, ${out.normalize.length} normalize cases`);
