// Writes test/fixtures/learn2/parity/words.json: what the website's shared words return (data/learn/words.js, R3 ruling W, and the
// Free lines of data/learn/allowance.js, ruling F) for a set of inputs: the labels, the time after a label, the counted names, the
// chapter's place. test/unit/learn2/data/learn_words_parity_test.dart holds the app's port (lib/features/learn2/data/learn_words.dart)
// to every output exactly.
//
// Run from flutter_app:  node tool/learn2_parity/words.mjs
// The web worktree is the sibling folder wt-1102-web (origin/main; LEARN2_WEB overrides it). Nothing is generated by a model and
// nothing leaves this machine: the script only reads the web's two modules and writes one JSON file.
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..', '..');
const web = resolve(process.env.LEARN2_WEB || resolve(app, '..', '..', 'wt-1102-web'));
const words = await import(pathToFileURL(resolve(web, 'data/learn/words.js')).href);
const free = await import(pathToFileURL(resolve(web, 'data/learn/allowance.js')).href);

let commit = 'unknown';
try { commit = execSync('git rev-parse --short=9 HEAD', { cwd: web }).toString().trim(); } catch { /* not a git folder */ }

const numbers = [0, 1, 2, 3, 5, 9, 10, 12, 46, 100, 0.2, 0.5, 1.2, 2.7, 6.2, 59.9, -3, -0.5, NaN, null, undefined, '4', 'x'];
const label = (v) => (v === undefined ? null : Number.isNaN(v) ? 'NaN' : v === Infinity ? 'Infinity' : v);

const places = [undefined, null, {}, { n: 0, of: 14 }, { n: 5 }, { n: 5, of: 0 }, { n: 5, of: 14 }, { n: 1, of: 1 }, { n: 14, of: 14 }, { n: '3', of: '7' }, { n: -2, of: 14 }, { n: 2.9, of: 14.4 }];

const out = {
  web: `wt-1102-web ${commit}`,
  note: "Written by tool/learn2_parity/words.mjs from the web's own words.js and allowance.js. Do not edit by hand.",
  words: words.WORDS,
  free: {
    doneHeadline: free.FREE_DONE_HEADLINE, doneLine: free.FREE_DONE_LINE, sessionDone: free.FREE_SESSION_DONE, endLine: free.FREE_END_LINE,
    capped: free.FREE_CAPPED, cardsOnly: free.FREE_CARDS_ONLY,
  },
  whole: numbers.map((n) => ({ n: label(n), out: words.wholeMinutes(n) })),
  withMinutes: numbers.map((n) => ({ n: label(n), out: words.withMinutes('Continue', n) })),
  fixMistakes: numbers.flatMap((n) => [[n, 3], [n, 0.4]].map(([c, m]) => ({ n: label(c), minutes: m, out: words.fixMistakes(c, m) }))),
  reviseDue: numbers.flatMap((n) => [[n, 3], [n, 1]].map(([c, m]) => ({ n: label(c), minutes: m, out: words.reviseDue(c, m) }))),
  reviseQuestions: numbers.map((n) => ({ n: label(n), out: words.reviseQuestions(n) })),
  pileLabel: numbers.map((n) => ({ n: label(n), out: words.pileLabel(n) })),
  // Round 5 (LK38): when a rated card comes back, in words, and the three phrasings built from them.
  returnWords: [0, 0.4, 1, 1.49, 1.5, 2, 2.4, 3, 8, 13, 13.4, 14, 20, 35, 55, 55.4, 56, 95, 200, -3, NaN, null, undefined].map((d) => ({ days: label(d), out: words.returnWords(d) })),
  backs: ['tomorrow', 'in 3 days', 'in 2 weeks'].map((w) => ({ words: w, stamp: words.backStamp(w), line: words.backLine(w), missedInRun: words.missedWords(w, true), missed: words.missedWords(w, false) })),
  places: places.map((place) => ({ place: place ?? null, place_label: words.chapterPlace(place), short: words.chapterShort(place) })),
};

const file = resolve(app, 'test/fixtures/learn2/parity/words.json');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, `${JSON.stringify(out, null, 1)}\n`);
console.log(`wrote ${file}: ${numbers.length} numbers, ${places.length} places`);
