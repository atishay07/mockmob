// Builds the home hero's Mobi poster (LK32, hero.md item 9): his first frame as a static SVG string, so the hero
// shows the real rigged Mobi with 0 image bytes and no script before the rig (MobiReact) loads on idle.
//
//   node scripts/brand/build-mobi-poster.mjs
//
// It renders the same MobiFigure the live Mobi draws (src/components/brand/MobiFigure.jsx), with the same first
// frame MobiReact computes for `act="idle"` (poseRig(moves, book, 'idle', 'calm', { live: true })), to plain markup,
// and writes src/components/landing/mobiPoster.generated.js. When the rig takes over it paints that same frame, so
// nothing jumps. The `appear` act's own first frame has his eyes shut and his body 10 units low (it is the start of a
// rise), which would read as a broken poster while the rig loads, so the entrance is the poster's CSS rise
// (hero-scene.css) and the rig starts from his standing frame. Run it again whenever the rig or the figure changes.
//
// JSX and the '@/...' alias are handled by a small module hook using the SWC that ships with Next; CSS imports are
// empty and JSON imports are plain default exports. Nothing here runs in the app.

import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = pathToFileURL(path.join(ROOT, 'src') + path.sep).href;
const OUT = path.join(ROOT, 'src', 'components', 'landing', 'mobiPoster.generated.js');
const PREFIX = 'mbposter-';

const hooks = `
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(${JSON.stringify(pathToFileURL(path.join(ROOT, 'package.json')).href)});
const swc = require('next/dist/build/swc');
let ready = null;
const SRC = ${JSON.stringify(SRC)};
const EXT = ['', '.js', '.jsx', '.mjs', '/index.js'];
export async function resolve(specifier, context, next) {
  let spec = specifier;
  if (spec.startsWith('@/')) spec = new URL(spec.slice(2), SRC).href;
  if ((spec.startsWith('.') || spec.startsWith('file:')) && context.parentURL?.startsWith('file:')) {
    const base = new URL(spec, context.parentURL);
    for (const ext of EXT) {
      const url = new URL(base.href + ext);
      if (existsSync(fileURLToPath(url)) && !fileURLToPath(url).endsWith('\\\\') ) {
        try { if (require('node:fs').statSync(fileURLToPath(url)).isFile()) return next(url.href, context); } catch {}
      }
    }
  }
  return next(spec, context);
}
export async function load(url, context, next) {
  if (url.endsWith('.css')) return { format: 'module', source: 'export default {};', shortCircuit: true };
  if (url.endsWith('.json')) return { format: 'module', source: 'export default ' + readFileSync(fileURLToPath(url), 'utf8') + ';', shortCircuit: true };
  if (url.endsWith('.jsx')) {
    ready ||= Promise.resolve(swc.loadBindings?.());
    await ready;
    const out = await swc.transform(readFileSync(fileURLToPath(url), 'utf8'), { jsc: { parser: { syntax: 'ecmascript', jsx: true }, transform: { react: { runtime: 'automatic' } }, target: 'es2022' }, module: { type: 'es6' } });
    return { format: 'module', source: out.code, shortCircuit: true };
  }
  if (url.startsWith('file:') && url.endsWith('.js') && url.startsWith(SRC)) return { format: 'module', source: readFileSync(fileURLToPath(url), 'utf8'), shortCircuit: true };
  return next(url, context);
}
`;
register(`data:text/javascript,${encodeURIComponent(hooks)}`, import.meta.url);

const { createElement } = await import('react');
const { renderToStaticMarkup } = await import('react-dom/server');
const { default: MobiFigure } = await import(new URL('components/brand/MobiFigure.jsx', SRC).href);
const { poseRig } = await import(new URL('components/brand/mobiPose.js', SRC).href);
const { book, moves } = await import(new URL('components/brand/mobiBook.js', SRC).href);

const initial = poseRig(moves, book, 'idle', 'calm', { live: true });
let svg = renderToStaticMarkup(createElement(MobiFigure, { initial, px: 1 }));
// useId's prefix is the render's own; the poster gets a fixed one so its gradient ids never meet a live Mobi's.
const used = svg.match(/id="(mb[^"-]*-)/)?.[1];
if (!used) throw new Error('no gradient prefix found in the rendered figure');
svg = svg.split(used).join(PREFIX);
const bytes = Buffer.byteLength(svg);
writeFileSync(OUT, `// GENERATED by scripts/brand/build-mobi-poster.mjs. Do not edit by hand; run the script again.\n// Mobi's first frame (act idle, mood calm, standing at ease) as static SVG: ${bytes} bytes.\nexport const MOBI_POSTER_SVG = ${JSON.stringify(svg)};\n`);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${bytes} bytes of SVG`);
