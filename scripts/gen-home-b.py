"""python scripts/gen-home-b.py

Writes src/app/home-b/page.js from src/app/page.js (owner, 24 Nov 2026: a second version of the home page to compare, shared
as a link, not indexed). Version B differs from "/" in one thing: the one frame "Your whole CUET prep, in one place" is taken
apart again. In its place the other features scroll as their own sections (the tour deck, Key cards, Bring a mistake), and
the exam screen section sits below the Mistake Lab. Everything else is the home page, so run this again after page.js changes.
"""
import io, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
src = io.open(os.path.join(ROOT, 'src/app/page.js'), encoding='utf-8', newline='').read()
crlf = '\r\n' in src
s = src.replace('\r\n', '\n')


def once(a, b):
    global s
    assert s.count(a) == 1, (a[:80], s.count(a))
    s = s.replace(a, b)


# the page's own sheet, one folder up
once("import './home-sheets.css';", "import '@/app/home-sheets.css';")

# imports the separate sections need
once("import OnePlaceGate from '@/components/landing/OnePlaceGate';\n",
     "import { ExamScreen } from '@/components/landing/ExamScreen';\n"
     "import TourDeck from '@/components/landing/TourDeck';\n"
     "import KeyCardsDemo from '@/components/landing/KeyCardsDemo';\n"
     "import BringMistakeBlock from '@/components/landing/BringMistakeBlock';\n"
     "import { KEY_CARDS_HEAD } from '@/components/landing/keyCardsCopy.mjs';\n"
     "import { BrandIcon } from '@/components/brand/BrandIcon';\n"
     "import { TOUR_HEAD } from '@/components/landing/homeCopy.mjs';\n")

# the one frame -> the separate, scrolling sections
start = s.index("        <Later><section className=\"lp-sec op\" id=\"your-prep\" aria-labelledby=\"op-title\">")
end = s.index("        </section></Later>", start) + len("        </section></Later>")
separate = """        <Later><section className="lp-sec lp-sec--tour lp-pos-host" id="your-prep">
          <div className="mm-wrap">
            <Reveal className="lp-head lp-head--left">
              <h2 className="lp-h2">{TOUR_HEAD.h2}</h2>
              <p className="lp-sub">{TOUR_HEAD.sub}</p>
            </Reveal>
            <TourDeck slides={TOUR} samples={TOUR_SAMPLES} />
          </div>
        </section></Later>

        {KEY_CARDS ? (
          <Later><section className="lp-sec lp-kc" id="key-cards" aria-labelledby="key-cards-title" data-section-name={KEY_CARDS_HEAD.stamp}>
            <div className="mm-wrap lp-kc__grid">
              <Reveal className="lp-head lp-head--left lp-kc__head">
                <p className="lp-kc__stamp"><BrandIcon name="keycards" size={32} style={{ '--bi-size': '28px' }} />{KEY_CARDS_HEAD.stamp}</p>
                <h2 className="lp-h2" id="key-cards-title">{headPhrases(KEY_CARDS_HEAD.h2).map((phrase, i, all) => <span key={phrase} className="lp-kc__phrase"><Marked text={i < all.length - 1 ? `${phrase} ` : phrase} marks={[['on time.', { mark: 'circle', tone: 'brand' }]]} /></span>)}</h2>
                <p className="lp-sub">{KEY_CARDS_HEAD.sub}</p>
              </Reveal>
              <KeyCardsDemo cards={KEY_CARDS.cards} keys={KEY_CARDS.keys} bank={KEY_CARDS.bank} subjects={KEY_CARDS.subjects} />
            </div>
          </section></Later>
        ) : null}

        <Later><BringMistakeBlock photo={MISTAKE_PHOTO_ON} credits={MISTAKE_CREDITS} photoCredits={MISTAKE_PHOTO_CREDITS} /></Later>"""
s = s[:start] + separate + s[end:]

# not indexed; the canonical address stays "/"
once("export default function LandingPage() {", "export const metadata = { robots: { index: false, follow: false }, alternates: { canonical: '/' } };\n\nexport default function LandingPageB() {")
once("import { CREATORS_SUB, ONE_PLACE, freeFaq, mobiPrice } from '@/components/landing/onePlaceCopy.mjs';", "import { CREATORS_SUB, freeFaq, mobiPrice } from '@/components/landing/onePlaceCopy.mjs';")

# the exam screen, below the Mistake Lab
lab = s.index('id="inside-the-lab"')
lab_end = s.index("        </section></Later>", lab) + len("        </section></Later>")
s = s[:lab_end] + "\n\n        {/* Version B: the exam screen (mock and NTA screen) has its own section, below the Mistake Lab. */}\n        <Later><ExamScreen /></Later>" + s[lab_end:]

s = ("// GENERATED by scripts/gen-home-b.py from src/app/page.js: version B of the home page, for comparing (owner, 24 Nov 2026).\n"
     "// Not indexed, not linked from the site. Edit page.js or the script, never this file.\n") + s
if crlf:
    s = s.replace('\n', '\r\n')
os.makedirs(os.path.join(ROOT, 'src/app/home-b'), exist_ok=True)
io.open(os.path.join(ROOT, 'src/app/home-b/page.js'), 'w', encoding='utf-8', newline='').write(s)
print('wrote src/app/home-b/page.js', len(s))
