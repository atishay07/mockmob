#!/usr/bin/env node
// Writes the Syllabus v2 migration and its undo from data/cuet_syllabus.js, so the database rows match the code exactly.
//   node scripts/syllabus/build-syllabus-v2-sql.mjs          (rewrites both files)
//   node scripts/syllabus/build-syllabus-v2-sql.mjs --check  (exits 1 when the saved files differ from what it would write)
// It writes files only. It never connects to a database; applying the migration is the orchestrator's step.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHAPTERS, CHAPTER_ALIASES, RETIRED_CHAPTERS, SPLIT_CHAPTERS, SYLLABUS_SUBJECTS, unitsFor } from '../../data/cuet_syllabus.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const MIGRATION = join(root, 'supabase', 'migrations', '20261031130000_syllabus_v2.sql');
export const UNDO = join(root, 'supabase', 'undo', '20261031130000_syllabus_v2.undo.sql');

// Section 5 merges that move question rows (old stored name -> surviving stored name). Legacy anchor names
// (Partnership, Management, GK, Grammar, National Income, Dissolution) are read-time aliases only.
// "Communication Technologies" -> "Data Communication" is a merge after review: the re-tag file moves those rows.
export const MERGE_RENAMES = Object.freeze([
  ['accountancy', 'Dissolution of Partnership', 'Dissolution of Partnership Firm'],
  ['accountancy', 'Computerised Accounting System', 'Computerized Accounting System'],
  ['economics', 'National Income Accounting', 'National Income & Related Aggregates'],
  ['economics', 'Determination of Income and Employment', 'Income Determination'],
  ['business_studies', 'Business Finance', 'Financial Management'],
  ['business_studies', 'Marketing', 'Marketing Management'],
  ['mathematics', 'Vectors', 'Vector Algebra'],
  ['physics', 'Electronic Devices', 'Semiconductor Electronics'],
  ['chemistry', 'd and f Block Elements', 'd- and f-Block Elements'],
  ['computer_science', 'MySQL', 'Structured Query Language'],
  ['computer_science', 'File Handling in Python', 'File Handling'],
]);

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const idSlug = (value) => String(value).toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
const subjectsList = SYLLABUS_SUBJECTS.map(q).join(', ');

export function migrationSql() {
  for (const [subject, from, to] of MERGE_RENAMES) {
    if (CHAPTER_ALIASES[subject]?.[from] !== to) throw new Error(`merge not in CHAPTER_ALIASES: ${subject} ${from}`);
  }
  const unitRows = [];
  for (const subject of SYLLABUS_SUBJECTS) {
    for (const entry of unitsFor(subject)) unitRows.push(`  (${q(`${subject}__s2u${entry.unitOrder}`)}, ${q(subject)}, ${q(entry.unit)}, ${entry.unitOrder - 1})`);
  }
  const chapterRows = CHAPTERS.map((c) => `  (${q(`${c.subject}__${idSlug(c.name)}`)}, ${q(c.subject)}, ${q(c.name)}, ${q(c.unit)}, ${c.unitOrder * 100 + c.order - 1}, ${q(c.key)}, ${q(c.title)}, ${q(c.section)})`);
  const retiredRows = [];
  for (const [subject, map] of Object.entries(RETIRED_CHAPTERS)) for (const [name, reason] of Object.entries(map)) retiredRows.push(`  (${q(subject)}, ${q(name)}, ${q(reason)})`);
  for (const [subject, map] of Object.entries(SPLIT_CHAPTERS)) for (const name of Object.keys(map)) retiredRows.push(`  (${q(subject)}, ${q(name)}, 'split_pending_retag')`);
  for (const [subject, map] of Object.entries(CHAPTER_ALIASES)) for (const name of Object.keys(map)) retiredRows.push(`  (${q(subject)}, ${q(name)}, 'merged')`);
  const offRows = [];
  for (const [subject, map] of Object.entries(RETIRED_CHAPTERS)) for (const name of Object.keys(map)) offRows.push(`  (${q(subject)}, ${q(name)})`);
  const renameRows = MERGE_RENAMES.map(([s, from, to]) => `  (${q(s)}, ${q(from)}, ${q(to)})`);

  return `-- ============================================================
-- MockMob migration 20261031130000 - Syllabus v2 (CUET 2026 units, NCERT chapters, retired chapters)
-- Generated by scripts/syllabus/build-syllabus-v2-sql.mjs from data/cuet_syllabus.js. Do not edit by hand.
-- Rulings: docs/brain/intel-1031/syllabus-verified.md. Undo: supabase/undo/20261031130000_syllabus_v2.undo.sql.
-- Saved only. Dry-run on a schema copy first. Never deletes a row: retired chapters keep their rows and questions,
-- the questions get is_cuet_syllabus=false, and every question it changes is recorded in syllabus_v2_changes.
-- ============================================================

begin;

-- ---- New chapter fields ---------------------------------------------------
alter table public.chapters add column if not exists retired_reason text;
alter table public.chapters add column if not exists chapter_key text;
alter table public.chapters add column if not exists title text;
alter table public.chapters add column if not exists section text;
create unique index if not exists chapters_chapter_key_key on public.chapters (chapter_key);

-- ---- What the undo needs ----------------------------------------------------
create table if not exists public.syllabus_v2_changes (
  id bigint generated always as identity primary key,
  question_id text not null,
  old_chapter text,
  new_chapter text,
  old_flag boolean,
  kind text not null default 'migration',
  changed_at timestamptz not null default now()
);
create index if not exists syllabus_v2_changes_question_idx on public.syllabus_v2_changes (question_id, id);
alter table public.syllabus_v2_changes enable row level security;
revoke all on public.syllabus_v2_changes from anon, authenticated;

create table if not exists public.syllabus_v2_chapter_snapshot as
  select id, subject_id, name, sort_order, unit_id from public.chapters where subject_id in (${subjectsList});
create table if not exists public.syllabus_v2_unit_snapshot as
  select id, subject_id, name, sort_order from public.units where subject_id in (${subjectsList});
alter table public.syllabus_v2_chapter_snapshot enable row level security;
alter table public.syllabus_v2_unit_snapshot enable row level security;
revoke all on public.syllabus_v2_chapter_snapshot from anon, authenticated;
revoke all on public.syllabus_v2_unit_snapshot from anon, authenticated;

-- ---- Units: the exact CUET 2026 unit titles (existing rows with the same name keep their ids) ----------------
-- Units no longer listed keep their rows; they hold no live chapter after this, so no picker shows them.
update public.units set sort_order = 1000 + sort_order where subject_id in (${subjectsList}) and sort_order < 1000;
insert into public.units (id, subject_id, name, sort_order) values
${unitRows.join(',\n')}
on conflict (subject_id, name) do update set sort_order = excluded.sort_order;

-- ---- Chapters: live chapters upserted by (subject_id, name), keeping existing ids ---------------------------
create temporary table syllabus_v2_live (id text, subject_id text, name text, unit_name text, sort_order int, chapter_key text, title text, section text) on commit drop;
insert into syllabus_v2_live values
${chapterRows.join(',\n')};

-- Free the keys first, so a retired or merged row never holds a live chapter's key.
update public.chapters set chapter_key = null where subject_id in (${subjectsList});

insert into public.chapters (id, subject_id, name, sort_order)
select l.id, l.subject_id, l.name, l.sort_order from syllabus_v2_live l
where not exists (select 1 from public.chapters c where c.subject_id = l.subject_id and c.name = l.name)
on conflict (id) do nothing;

update public.chapters c set
  unit_id = u.id,
  sort_order = l.sort_order,
  chapter_key = l.chapter_key,
  title = l.title,
  section = l.section,
  retired_reason = null
from syllabus_v2_live l
join public.units u on u.subject_id = l.subject_id and u.name = l.unit_name
where c.subject_id = l.subject_id and c.name = l.name;

-- Retired chapters (not_in_cuet_2026), splits waiting for the re-tag, and merged twins: kept, never offered.
create temporary table syllabus_v2_off (subject_id text, name text, reason text) on commit drop;
insert into syllabus_v2_off values
${retiredRows.join(',\n')};
update public.chapters c set retired_reason = o.reason, unit_id = null, chapter_key = null, title = null, section = null
from syllabus_v2_off o
where c.subject_id = o.subject_id and c.name = o.name;

-- Any other chapter row of these subjects that is not live now (old placeholders such as English "Grammar & Usage").
update public.chapters c set retired_reason = coalesce(c.retired_reason, 'not_in_syllabus_v2'), unit_id = null, chapter_key = null
where c.subject_id in (${subjectsList})
  and not exists (select 1 from syllabus_v2_live l where l.subject_id = c.subject_id and l.name = c.name);

-- ---- Questions: retired chapters leave every student surface ---------------------------------------------------
create temporary table syllabus_v2_retired (subject text, chapter text) on commit drop;
insert into syllabus_v2_retired values
${offRows.join(',\n')};

insert into public.syllabus_v2_changes (question_id, old_chapter, new_chapter, old_flag, kind)
select q.id::text, q.chapter, q.chapter, q.is_cuet_syllabus, 'retire'
from public.questions q
join syllabus_v2_retired r on r.subject = q.subject and r.chapter = q.chapter
where q.is_cuet_syllabus is distinct from false;

update public.questions q set is_cuet_syllabus = false
from syllabus_v2_retired r
where r.subject = q.subject and r.chapter = q.chapter and q.is_cuet_syllabus is distinct from false;

-- ---- Questions: section 5 merges move to the surviving stored name ---------------------------------------------
-- Evidence, index, agent and fit hashes taken under the old label still match (data/content_evidence.js
-- contentHashMatches), so a renamed question keeps its scores.
create temporary table syllabus_v2_renames (subject text, old_chapter text, new_chapter text) on commit drop;
insert into syllabus_v2_renames values
${renameRows.join(',\n')};

insert into public.syllabus_v2_changes (question_id, old_chapter, new_chapter, old_flag, kind)
select q.id::text, q.chapter, r.new_chapter, q.is_cuet_syllabus, 'merge'
from public.questions q
join syllabus_v2_renames r on r.subject = q.subject and r.old_chapter = q.chapter;

update public.questions q set chapter = r.new_chapter
from syllabus_v2_renames r
where r.subject = q.subject and r.old_chapter = q.chapter;

-- ---- The re-tag hook ------------------------------------------------------------------------------------------
-- Applies data/syllabus/retag-2026-10-31.json ([{ id, subject, from, to, why }]) once the orchestrator's agent pass has
-- filled it: node scripts/syllabus/retag-sql.mjs prints the call. A row moves only while it still sits in \`from\`,
-- and only into a live chapter of its subject; every move is recorded for the undo. A question leaving a retired chapter
-- gets back the is_cuet_syllabus value it had before this migration.
create or replace function public.apply_syllabus_retag(p_items jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  moved integer := 0;
  current_row record;
  restored boolean;
begin
  for item in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) loop
    select id, subject, chapter, is_cuet_syllabus into current_row
      from public.questions where id::text = item->>'id' and subject = item->>'subject' for update;
    if not found or current_row.chapter is distinct from item->>'from' then continue; end if;
    if not exists (select 1 from public.chapters c where c.subject_id = item->>'subject' and c.name = item->>'to' and c.retired_reason is null and c.chapter_key is not null) then
      continue;
    end if;
    select s.old_flag into restored from public.syllabus_v2_changes s
      where s.question_id = current_row.id::text and s.kind = 'retire' order by s.id asc limit 1;
    insert into public.syllabus_v2_changes (question_id, old_chapter, new_chapter, old_flag, kind)
      values (current_row.id::text, current_row.chapter, item->>'to', current_row.is_cuet_syllabus, 'retag');
    update public.questions set
      chapter = item->>'to',
      is_cuet_syllabus = case when exists (select 1 from public.syllabus_v2_changes s where s.question_id = current_row.id::text and s.kind = 'retire') then restored else is_cuet_syllabus end
      where id = current_row.id;
    moved := moved + 1;
  end loop;
  return moved;
end;
$$;
revoke all on function public.apply_syllabus_retag(jsonb) from public, anon, authenticated;

commit;
`;
}

export function undoSql() {
  return `-- ============================================================
-- Undo for 20261031130000_syllabus_v2 (generated by scripts/syllabus/build-syllabus-v2-sql.mjs).
-- Puts every question the migration or the re-tag hook changed back to its first recorded chapter and flag, restores the
-- chapter and unit rows from the snapshots, removes the rows and columns the migration added.
-- ============================================================

begin;

update public.questions q set chapter = s.old_chapter, is_cuet_syllabus = s.old_flag
from (
  select distinct on (question_id) question_id, old_chapter, old_flag
  from public.syllabus_v2_changes order by question_id, id asc
) s
where q.id::text = s.question_id;

update public.chapters c set name = s.name, sort_order = s.sort_order, unit_id = s.unit_id
from public.syllabus_v2_chapter_snapshot s
where c.id = s.id;

delete from public.chapters c
where c.subject_id in (${subjectsList})
  and not exists (select 1 from public.syllabus_v2_chapter_snapshot s where s.id = c.id);

update public.units u set name = s.name, sort_order = s.sort_order
from public.syllabus_v2_unit_snapshot s
where u.id = s.id;

delete from public.units u
where u.subject_id in (${subjectsList})
  and not exists (select 1 from public.syllabus_v2_unit_snapshot s where s.id = u.id)
  and not exists (select 1 from public.chapters c where c.unit_id = u.id);

drop function if exists public.apply_syllabus_retag(jsonb);
drop index if exists public.chapters_chapter_key_key;
alter table public.chapters drop column if exists retired_reason;
alter table public.chapters drop column if exists chapter_key;
alter table public.chapters drop column if exists title;
alter table public.chapters drop column if exists section;
drop table if exists public.syllabus_v2_chapter_snapshot;
drop table if exists public.syllabus_v2_unit_snapshot;
drop table if exists public.syllabus_v2_changes;

commit;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = [[MIGRATION, migrationSql()], [UNDO, undoSql()]];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([path, text]) => { try { return readFileSync(path, 'utf8') !== text; } catch { return true; } });
    for (const [path] of stale) console.error(`stale: ${path}`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [path, text] of files) writeFileSync(path, text);
  console.log(`wrote ${files.map(([path]) => path).join(', ')}`);
}
