// Generates shared/tokens.css (the web's CSS variables) from shared/tokens.json.
//
//   node shared/build-tokens.mjs           write shared/tokens.css
//   node shared/build-tokens.mjs --check   exit 1 when tokens.css is out of date
//
// The output has three layers:
//   1. fixed values on :root (brand, both palettes as --mm-night-* and --mm-day-*, fonts, type,
//      space, radii, targets, motion, glass);
//   2. theme roles (--mm-ground, --mm-ink ...) that follow <html data-theme>, Night by default;
//      .mm-night and .mm-day pin a subtree to one palette (a product still on a light page);
//   3. one .type-<role> class per type role.
// The Dart theme is generated by the app lane, not here.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = path.join(here, 'tokens.json');
export const TOKENS_CSS = path.join(here, 'tokens.css');

/** camelCase or ink2 to kebab-case (ink-2, line-strong, raised-2). */
export function kebab(name) {
  return String(name)
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d)/g, '$1-$2')
    .toLowerCase();
}

const VIEW_MIN = 375;
const VIEW_MAX = 1280;
const round = (n, places = 4) => Number(n.toFixed(places));

/** A fluid px size: `size` at 375px wide, growing linearly to `max` at 1280px. */
export function fluidSize(size, max) {
  if (!max || max <= size) return `${size}px`;
  const slope = (max - size) / (VIEW_MAX - VIEW_MIN);
  const intercept = size - slope * VIEW_MIN;
  return `clamp(${size}px, ${round(intercept, 2)}px + ${round(slope * 100, 3)}vw, ${max}px)`;
}

export function typeRole(role) {
  return {
    size: fluidSize(role.size, role.webMax),
    line: String(round(role.line / role.size, 3)),
    weight: String(role.weight),
    tracking: role.tracking ? `${round(role.tracking / 100, 4)}em` : '0',
    stretch: `${role.stretch ?? 100}%`,
  };
}

const ROLE_ORDER = (palette) => Object.keys(palette);

function block(selector, lines) {
  return `${selector} {\n${lines.map((line) => `  ${line}`).join('\n')}\n}\n`;
}

export function renderTokensCss(tokens) {
  const { color, shadow, font, type, space, radius, target, motion, glass, dock } = tokens;
  const fixed = [];
  fixed.push('/* Brand */');
  for (const [k, v] of Object.entries(color.brand)) fixed.push(`--mm-${kebab(k)}: ${v};`);
  for (const theme of ['night', 'day']) {
    fixed.push(`/* ${theme === 'night' ? 'Night palette' : 'Daylight palette'}, fixed */`);
    for (const [k, v] of Object.entries(color[theme])) fixed.push(`--mm-${theme}-${kebab(k)}: ${v};`);
    for (const [k, v] of Object.entries(shadow[theme])) fixed.push(`--mm-${theme}-shadow-${kebab(k)}: ${v};`);
  }
  fixed.push('/* Fonts (the --font-* variables come from next/font in src/app/layout.js) */');
  for (const [k, f] of Object.entries(font)) fixed.push(`--mm-font-${kebab(k)}: var(${f.cssVar}), ${f.fallback};`);
  fixed.push('/* Type roles: size, line height, weight, tracking, width */');
  for (const [name, role] of Object.entries(type)) {
    if (name.startsWith('$')) continue;
    const t = typeRole(role);
    const base = `--mm-type-${kebab(name)}`;
    fixed.push(`${base}-size: ${t.size}; ${base}-line: ${t.line}; ${base}-weight: ${t.weight}; ${base}-tracking: ${t.tracking};`);
  }
  fixed.push('/* Space, radii, targets */');
  for (const [k, v] of Object.entries(space)) fixed.push(`--mm-space-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(radius)) fixed.push(`--mm-radius-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(target)) fixed.push(`--mm-target-${kebab(k)}: ${v}px;`);
  fixed.push('/* Motion */');
  for (const [k, v] of Object.entries(motion.curve)) fixed.push(`--mm-ease-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(motion.duration)) fixed.push(`--mm-dur-${kebab(k)}: ${v}ms;`);
  fixed.push(`--mm-pressed-scale: ${motion.pressedScale};`);
  fixed.push('/* Glass (chrome only) and the dock */');
  for (const [k, v] of Object.entries(glass)) fixed.push(`--mm-glass-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(dock)) fixed.push(`--mm-dock-${kebab(k)}: ${v}px;`);

  const roles = (theme) => [
    ...ROLE_ORDER(color[theme]).map((k) => `--mm-${kebab(k)}: var(--mm-${theme}-${kebab(k)});`),
    ...Object.keys(shadow[theme]).map((k) => `--mm-shadow-${kebab(k)}: var(--mm-${theme}-shadow-${kebab(k)});`),
    `color-scheme: ${theme === 'night' ? 'dark' : 'light'};`,
  ];

  const typeClasses = Object.entries(type)
    .filter(([name]) => !name.startsWith('$'))
    .map(([name, role]) => {
      const base = `--mm-type-${kebab(name)}`;
      const lines = [
        `font-family: var(--mm-font-${role.font});`,
        `font-size: var(${base}-size);`,
        `line-height: var(${base}-line);`,
        `font-weight: var(${base}-weight);`,
        `letter-spacing: var(${base}-tracking);`,
      ];
      if (role.font === 'display') lines.push(`font-stretch: ${role.stretch ?? 100}%;`);
      lines.push('font-variant-numeric: tabular-nums;');
      return block(`.type-${kebab(name)}`, lines);
    })
    .join('');

  return [
    '/* Generated by shared/build-tokens.mjs from shared/tokens.json. Do not edit by hand. */',
    block(':root', fixed),
    '/* Theme roles. Night is the default identity; <html data-theme="light"> switches to Daylight. */',
    block(":root,\n[data-theme='dark'],\n.mm-night", roles('night')),
    block("[data-theme='light'],\n.mm-day", roles('day')),
    '/* Type roles (tabular figures everywhere, as in the app). */',
    typeClasses,
  ].join('\n');
}

export function readTokens() {
  return JSON.parse(readFileSync(TOKENS_JSON, 'utf8'));
}

function main(argv) {
  const css = renderTokensCss(readTokens());
  if (argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(TOKENS_CSS, 'utf8'); } catch { /* missing counts as stale */ }
    if (current.replace(/\r\n/g, '\n') !== css) {
      console.error('shared/tokens.css is out of date. Run: node shared/build-tokens.mjs');
      process.exit(1);
    }
    console.log('shared/tokens.css is up to date.');
    return;
  }
  writeFileSync(TOKENS_CSS, css);
  console.log(`Wrote ${path.relative(process.cwd(), TOKENS_CSS)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
