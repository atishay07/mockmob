test('every job pose is in the manifest with its size, and the wave has its six cells', () => {
  for (const pose of ['greeting', 'attentive', 'thinking', 'pointing', 'celebrating', 'encouraging', 'idle', 'reading', 'magnifier', 'camera', 'calendar', 'deskHello', 'wave']) {
    const art = MANIFEST[pose];
    assert.ok(art && art.src.startsWith('/brand/mascot/') && art.width > 0 && art.height > 0, pose);
    assert.ok(art.bytes < 60 * 1024, `${pose} stays small (${art.bytes} bytes)`);
  }
  assert.equal(MANIFEST.waveSheet.cells, 6);
  assert.equal(MANIFEST.waveSheet.width, MANIFEST.waveSheet.cellWidth * 6);
  const css = read('../../app/brand-pip.css');
  assert.match(css, /animation: pip-wave-cells 660ms steps\(6, jump-none\) 240ms 1 both;/, 'the wave plays once');
  assert.match(css, /html\[data-motion='reduced'\] \.pip-wave \{ display: none !important; \}/);
});

