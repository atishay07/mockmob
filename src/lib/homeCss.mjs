const HEADER = [
  '/* GENERATED by scripts/gen-home-css.mjs from the sheets listed in src/lib/homeCss.mjs (HOME_SHEETS). Do not edit this',
  '   file: edit the sheet named in the banner above a rule, then run `node scripts/gen-home-css.mjs` (a dev server rewrites',
  '   it by itself while it runs). The home page imports this one file, so a phone downloads one stylesheet, not seven. */',
];

const toLf = (text) => text.replace(/\r\n?/g, '\n');

/** Throws when a sheet would leak into the next one once joined: an open comment, string or block at its end. */
export function assertClosed(css, name) {
  let depth = 0;
  for (let i = 0; i < css.length; i += 1) {
    const ch = css[i];
    if (ch === '/' && css[i + 1] === '*') {
      const end = css.indexOf('*/', i + 2);
      if (end < 0) throw new Error(`${name}: a comment is never closed`);
      i = end + 1;
    } else if (ch === '"' || ch === "'") {
      let j = i + 1;
      while (j < css.length && css[j] !== ch && css[j] !== '\n') j += css[j] === '\\' ? 2 : 1;
      if (css[j] !== ch) throw new Error(`${name}: a string is never closed (offset ${i})`);
      i = j;
    } else if (ch === '{') depth += 1;
    else if (ch === '}') {
      depth -= 1;
      if (depth < 0) throw new Error(`${name}: a } closes nothing (offset ${i})`);
    }
  }
  if (depth !== 0) throw new Error(`${name}: ${depth} block(s) left open at the end`);
  const code = css.replace(/\/\*[\s\S]*?\*\//g, '');
  if (/@(import|charset|namespace)\b/.test(code)) {
    throw new Error(`${name}: @import, @charset and @namespace only work at the top of a file, so this sheet cannot be joined`);
  }
  // A relative url() resolves from the file it is written in; joined, it would resolve from home-sheets.css instead.
  const relative = code.match(/url\(\s*(?!['"]?(?:data:|\/|#|https?:))[^)]*\)/);
  if (relative) throw new Error(`${name}: ${relative[0]} is relative; use a root path (/...) so it works from the joined file`);
}

/** The joined file's text (LF line ends), from the sheets on disk. */
export function buildHomeCss({ root = ROOT, sheets = HOME_SHEETS } = {}) {
  const parts = [HEADER.join('\n')];
  for (const rel of sheets) {
    const css = toLf(readFileSync(path.join(root, rel), 'utf8')).replace(/^﻿/, '');
    assertClosed(css, rel);
    parts.push(`/* ==== ${rel} ==== */\n${css.replace(/\n+$/, '')}`);
  }
  return `${parts.join('\n\n')}\n`;
}

/** Writes the joined file when it differs from the sheets (line ends ignored). Returns { stale, wrote }. */
export function generate({ check = false, root = ROOT } = {}) {
  const file = path.join(root, BUNDLE);
  const next = buildHomeCss({ root });
  const current = existsSync(file) ? toLf(readFileSync(file, 'utf8')) : null;
  if (current === next) return { stale: false, wrote: false };
  if (check) return { stale: true, wrote: false };
  // Keep the checkout's line ends (Windows checkouts have CRLF), and swap the file in whole so a bundler never reads half.
  const eol = existsSync(file) && readFileSync(file, 'utf8').includes('\r\n') ? '\r\n' : '\n';
  const tmp = `${file}.tmp`;
  writeFileSync(tmp, eol === '\n' ? next : next.replace(/\n/g, eol));
  try { renameSync(tmp, file); } catch { writeFileSync(file, readFileSync(tmp)); }
  return { stale: true, wrote: true };
}

/** Rewrites the joined file whenever a sheet changes. For development only (next.config.mjs calls it under `next dev`). */
export function watchHomeCss({ root = ROOT, log = () => {} } = {}) {
  if (globalThis.__mmHomeCssWatch) return;
  globalThis.__mmHomeCssWatch = true;
  try { generate({ root }); } catch (error) { log(`home-sheets.css: ${error.message}`); }
  let timer = null;
  const rebuild = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try { if (generate({ root }).wrote) log('home-sheets.css rewritten'); } catch (error) { log(`home-sheets.css: ${error.message}`); }
    }, 80);
  };
  for (const rel of HOME_SHEETS) {
    try { watch(path.join(root, rel), rebuild).unref(); } catch { /* a missing sheet is reported by the next rebuild */ }
  }
}

export function main(argv = []) {
  if (argv.includes('--watch')) {
    watchHomeCss({ log: (line) => console.log(line) });
    console.log(`watching ${HOME_SHEETS.length} sheets; ${BUNDLE} follows them`);
    setInterval(() => {}, 1 << 30);
    return null;
  }
  const check = argv.includes('--check');
  const { stale, wrote } = generate({ check });
  if (check) {
    if (stale) { console.error(`${BUNDLE} is stale: run node scripts/gen-home-css.mjs`); return 1; }
    console.log(`${BUNDLE} is up to date`);
    return 0;
  }
  console.log(wrote ? `wrote ${BUNDLE}` : `${BUNDLE} already up to date`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const code = main(process.argv.slice(2));
  if (code !== null) process.exit(code);
}
