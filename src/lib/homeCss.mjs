// The home page's own stylesheets, served as one file (paint pass, 15 Nov 2026).
//
// "/" used to import its 23 own sheets one by one. Both bundlers then cut them into seven (Turbopack, production) to nine
// (webpack) separate render-blocking files, because five of the sheets are shared with other pages and the chunkers never
// merge across a shared one. On a budget phone over mobile data every one of those requests delays the first paint.
// So the home page imports one file, src/app/home-sheets.css: the 23 sheets joined, byte for byte, in the order the live
// site applied them (checked against www.mockmob.in on 15 Nov 2026), so every rule still wins or loses exactly as before.
// The sheets stay the source: edit them, never the joined file. Other pages keep importing the sheets they use.
// Where the joined file lands against the components' own sheets (scroll-story.css, du.css ...) is the bundler's choice, so
// no home rule may win over one of them by order alone: src/lib/cssCascade.mjs and data/tests/home_cascade_order.test.mjs.
//
//   node scripts/gen-home-css.mjs           write src/app/home-sheets.css
//   node scripts/gen-home-css.mjs --check   exit 1 when it is stale
//   node scripts/gen-home-css.mjs --watch   keep it current while you edit (a dev server does this by itself: next.config.mjs)
//
// The order is the cascade, not the age of the sheets. It is the order production served on 15 Nov 2026: hero-scene,
// r10-sample and r13-motion sit together after home.css because /daily shares those three, and both bundlers grouped them
// (so r10-sample and r13-motion came before desktop-scale ... r10-hero). Keep that order unless you mean to change the look.
// A new sheet for the home page goes at the end of the list (it then loads after every older layer), then run the script.

