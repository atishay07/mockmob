// One motion language for the app and the website. shared/motion-tokens.json (the same bytes as
// the app's copy) is the only source. This module turns it into:
//   1. the CSS custom properties at the top of src/app/motion-kit.css, between the
//      motion-tokens:start and motion-tokens:end lines (springs become linear() curves sampled from
//      the same physics Flutter runs), and
//   2. src/lib/motion/tokens.g.js, the same values for scripts (swaps, drags, count-ups).
// The app has the twin: flutter_app/tool/gen_motion_tokens.py writes motion_tokens.g.dart.
//
//   node scripts/gen-motion-tokens.mjs           write both files
//   node scripts/gen-motion-tokens.mjs --check   exit 1 when either is stale
//
// Haptics: the CSS block has none; tokens.g.js carries each haptic's `web` vibrate pattern (the app uses the `flutter` and
// `android` halves of the same entries).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { pressLiftLinear, reverseCubic, springLinear, springPeak } from './motion/spring.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, '..', '..');
export const TOKENS_PATH = path.join(ROOT, 'shared', 'motion-tokens.json');
export const CSS_PATH = path.join(ROOT, 'src', 'app', 'motion-kit.css');
export const JS_PATH = path.join(ROOT, 'src', 'lib', 'motion', 'tokens.g.js');

export const START_MARK = '/* motion-tokens:start (generated by scripts/gen-motion-tokens.mjs from shared/motion-tokens.json; do not edit) */';
export const END_MARK = '/* motion-tokens:end */';

/** Keys that are distances (logical px on the phone, CSS px here). */
export const DISTANCE_NUMBERS = new Set(['enterRise', 'axisTravel']);
export const DISTANCE_TRANSITION_KEYS = new Set(['slide', 'drift', 'travel', 'corner', 'recedeDrop']);

const IDENT = /^[a-z][A-Za-z0-9]*$/;

/** camelCase to kebab-case: inOut to in-out, momentT2 to moment-t2. */
export function kebab(name) {
  return String(name).replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

/** A JSON number as CSS or JS writes it (no trailing zeros, no exponent). */
export function num(value) {
  const n = Number(value);
  if (Number.isInteger(n)) return String(n);
  return String(Number(n.toFixed(6)));
}

export function cubic(points) {
  return `cubic-bezier(${points.map(num).join(', ')})`;
}

class TokenError extends Error {}

function fail(where, why) {
  throw new TokenError(`${where}: ${why}`);
}

/** Throws when the JSON breaks the shape both generators rely on. */
export function validateTokens(tokens) {
  for (const section of ['durations', 'curves', 'springs', 'numbers', 'counts', 'transitions']) {
    if (!tokens || typeof tokens[section] !== 'object' || Array.isArray(tokens[section])) fail(section, 'missing or not an object');
  }
  for (const [name, v] of Object.entries(tokens.durations)) {
    if (!IDENT.test(name)) fail(`durations.${name}`, 'not a lowerCamel name');
    if (!Number.isInteger(v) || v <= 0) fail(`durations.${name}`, 'must be a positive whole number of ms');
  }
  for (const [name, v] of Object.entries(tokens.curves)) {
    if (!Array.isArray(v) || v.length !== 4 || !v.every(Number.isFinite)) fail(`curves.${name}`, 'must be four numbers');
    if (v[0] < 0 || v[0] > 1 || v[2] < 0 || v[2] > 1) fail(`curves.${name}`, 'x1 and x2 must lie in 0..1');
  }
  for (const [name, v] of Object.entries(tokens.springs)) {
    if (!v || !Number.isInteger(v.ms) || v.ms <= 0) fail(`springs.${name}.ms`, 'must be a positive whole number');
    if (!Number.isFinite(v.bounce) || v.bounce < -1 || v.bounce > 1) fail(`springs.${name}.bounce`, 'must lie in -1..1');
  }
  for (const [name, v] of Object.entries(tokens.numbers)) if (!Number.isFinite(v)) fail(`numbers.${name}`, 'must be a number');
  for (const [name, v] of Object.entries(tokens.counts)) if (!Number.isInteger(v) || v < 0) fail(`counts.${name}`, 'must be a whole number');
  for (const [group, values] of Object.entries(tokens.transitions)) {
    for (const [key, v] of Object.entries(values)) {
      const where = `transitions.${group}.${key}`;
      if (key.endsWith('Ms')) { if (!Number.isInteger(v) || v <= 0) fail(where, 'must be a positive whole number of ms'); }
      else if (key === 'curve' || key.endsWith('Curve')) { if (!(v in tokens.curves)) fail(where, `names no curve (${v})`); }
      else if (!Number.isFinite(v)) fail(where, 'must be a number');
    }
  }
  return tokens;
}

export function readTokens(file = TOKENS_PATH) {
  return validateTokens(JSON.parse(readFileSync(file, 'utf8')));
}

/** Every spring with its linear() curve, settle time and peak. Slow-ish (fine sampling): cache it. */
export function sampleSprings(tokens) {
  const out = {};
  for (const [name, spring] of Object.entries(tokens.springs)) {
    const { easing, settleMs, stops } = springLinear(spring);
    out[name] = { ms: spring.ms, bounce: spring.bounce, settleMs, easing, stops, peak: springPeak(spring, settleMs) };
  }
  return out;
}

/** The press release with its lift past rest (the app's pressable), from pressedScale, snappy and release. */
export function samplePressLift(tokens) {
  return pressLiftLinear(tokens.springs, tokens.numbers.pressedScale);
}

/** One transition token as a CSS property name and value. */
export function transitionProperty(group, key, value) {
  if (key.endsWith('Ms')) return [`--mm-t-${kebab(group)}-${kebab(key.slice(0, -2))}-dur`, `${value}ms`];
  if (key === 'curve' || key.endsWith('Curve')) return [`--mm-t-${kebab(group)}-${kebab(key)}`, `var(--mm-ease-${kebab(value)})`];
  return [`--mm-t-${kebab(group)}-${kebab(key)}`, DISTANCE_TRANSITION_KEYS.has(key) ? `${num(value)}px` : num(value)];
}

/** The generated CSS block, markers included, lines joined with `eol`. */
export function cssBlock(tokens, { eol = '\n', springs = sampleSprings(tokens), lift = samplePressLift(tokens) } = {}) {
  const lines = [START_MARK, ':root {'];
  lines.push('  /* Durations (ms) */');
  for (const [name, v] of Object.entries(tokens.durations)) lines.push(`  --mm-dur-${kebab(name)}: ${v}ms;`);
  lines.push('  /* Curves */');
  for (const [name, v] of Object.entries(tokens.curves)) lines.push(`  --mm-ease-${kebab(name)}: ${cubic(v)};`);
  lines.push('  /* The same curves played backwards: an app animation in reverse, drawn as a forward CSS one */');
  for (const [name, v] of Object.entries(tokens.curves)) lines.push(`  --mm-ease-${kebab(name)}-reverse: ${cubic(reverseCubic(v))};`);
  lines.push('  /* Springs: the app\'s physics drawn as linear() over the time Flutter runs them (-dur) */');
  for (const [name, s] of Object.entries(springs)) {
    lines.push(`  /* ${name}: ${s.ms} ms, bounce ${num(s.bounce)}, peak ${s.peak.toFixed(4)} */`);
    lines.push(`  --mm-spring-${kebab(name)}: ${s.easing};`);
    lines.push(`  --mm-spring-${kebab(name)}-dur: ${s.settleMs}ms;`);
  }
  lines.push(`  /* A committed press lets go with a lift: up to ${lift.peakScale.toFixed(3)} from ${num(tokens.numbers.pressedScale)} on snappy, then release to 1 (progress space) */`);
  lines.push(`  --mm-press-lift: ${lift.easing};`);
  lines.push(`  --mm-press-lift-dur: ${lift.durationMs}ms;`);
  lines.push('  /* Distances, scales, shares and counts */');
  for (const [name, v] of Object.entries(tokens.numbers)) lines.push(`  --mm-${kebab(name)}: ${DISTANCE_NUMBERS.has(name) ? `${num(v)}px` : num(v)};`);
  for (const [name, v] of Object.entries(tokens.counts)) lines.push(`  --mm-${kebab(name)}: ${v};`);
  lines.push('  /* Page transitions */');
  for (const [group, values] of Object.entries(tokens.transitions)) {
    for (const [key, v] of Object.entries(values)) {
      const [prop, value] = transitionProperty(group, key, v);
      lines.push(`  ${prop}: ${value};`);
    }
  }
  lines.push('}');
  lines.push('/* Browsers without linear(): each spring falls back to the out curve over its nominal time. */');
  lines.push('@supports not (transition-timing-function: linear(0, 1)) {');
  lines.push('  :root {');
  for (const [name, s] of Object.entries(springs)) {
    lines.push(`    --mm-spring-${kebab(name)}: var(--mm-ease-out);`);
    lines.push(`    --mm-spring-${kebab(name)}-dur: ${s.ms}ms;`);
  }
  lines.push('    --mm-press-lift: var(--mm-ease-out);');
  lines.push(`    --mm-press-lift-dur: ${tokens.springs.release.ms}ms;`);
  lines.push('  }');
  lines.push('}');
  lines.push(END_MARK);
  return lines.join(eol);
}

function frozen(entries, indent = '  ') {
  return `Object.freeze({\n${entries.map(([k, v]) => `${indent}${k}: ${v},`).join('\n')}\n})`;
}

/** The generated JS module (LF). */
export function jsModule(tokens, { springs = sampleSprings(tokens), lift = samplePressLift(tokens) } = {}) {
  const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const out = [];
  out.push('// GENERATED by scripts/gen-motion-tokens.mjs from shared/motion-tokens.json. Do not edit by hand:');
  out.push('// change the JSON (the app reads the same file) and run `node scripts/gen-motion-tokens.mjs`.');
  out.push('// src/lib/motion-tokens.test.mjs fails when this file and the JSON disagree.');
  out.push('');
  out.push(`export const MOTION_TOKENS_VERSION = ${Number(tokens.version) || 0};`);
  out.push('');
  out.push('/** Durations in ms. */');
  out.push(`export const durations = ${frozen(Object.entries(tokens.durations).map(([k, v]) => [k, v]))};`);
  out.push('');
  out.push('/** Curves as the four cubic-bezier control values. */');
  out.push(`export const curves = ${frozen(Object.entries(tokens.curves).map(([k, v]) => [k, `Object.freeze([${v.map(num).join(', ')}])`]))};`);
  out.push('');
  out.push('/** Curves as CSS easing strings. */');
  out.push(`export const ease = ${frozen(Object.entries(tokens.curves).map(([k, v]) => [k, q(cubic(v))]))};`);
  out.push('');
  out.push('/** The same curves played backwards, as CSS easing strings. */');
  out.push(`export const easeReverse = ${frozen(Object.entries(tokens.curves).map(([k, v]) => [k, q(cubic(reverseCubic(v)))]))};`);
  out.push('');
  out.push('/** Springs: the JSON pair, the time Flutter runs it (settleMs) and its CSS linear() easing. */');
  out.push(`export const springs = ${frozen(Object.entries(springs).map(([k, s]) => [k, `Object.freeze({ ms: ${s.ms}, bounce: ${num(s.bounce)}, settleMs: ${s.settleMs}, peak: ${num(s.peak.toFixed(4))}, easing: ${q(s.easing)} })`]))};`);
  out.push('');
  out.push('/** A committed press letting go: a CSS easing in progress space (pressed to rest), its time and the scale it peaks at. */');
  out.push(`export const pressLift = Object.freeze({ easing: ${q(lift.easing)}, durationMs: ${lift.durationMs}, peakScale: ${num(lift.peakScale.toFixed(4))} });`);
  out.push('');
  out.push('/** Distances (px), scales and shares. */');
  out.push(`export const numbers = ${frozen(Object.entries(tokens.numbers).map(([k, v]) => [k, num(v)]))};`);
  out.push('');
  out.push('/** Whole counts. */');
  out.push(`export const counts = ${frozen(Object.entries(tokens.counts).map(([k, v]) => [k, v]))};`);
  out.push('');
  const webHaptics = Object.entries({ ...(tokens.haptics?.base || {}), ...(tokens.haptics?.verbs || {}) })
    .map(([k, v]) => [k, `Object.freeze([${(v.web || []).map(num).join(', ')}])`]);
  out.push('/** Vibrate patterns (ms on, off, on...) for the haptics the app also has; an empty pattern is a no-op. */');
  out.push(`export const haptics = ${frozen(webHaptics)};`);
  out.push('');
  out.push('/** Page transitions, as the app\'s router draws them. Curves are names in `curves`. */');
  out.push(`export const transitions = ${frozen(Object.entries(tokens.transitions).map(([g, values]) => [g, `Object.freeze({ ${Object.entries(values).map(([k, v]) => `${k}: ${typeof v === 'string' ? q(v) : num(v)}`).join(', ')} })`]))};`);
  out.push('');
  return out.join('\n');
}

const toLf = (text) => text.replace(/\r\n/g, '\n');

/** `css` with its generated block replaced (or added before the first :root). Keeps the file's line endings. */
export function replaceBlock(css, block) {
  const eol = css.includes('\r\n') ? '\r\n' : '\n';
  const body = block.split('\n').join(eol).replace(/\r\r\n/g, '\r\n');
  const start = css.indexOf('/* motion-tokens:start');
  const end = css.indexOf(END_MARK);
  if (start !== -1 && end > start) return css.slice(0, start) + body + css.slice(end + END_MARK.length);
  const at = css.indexOf(':root {');
  if (at === -1) return body + eol + eol + css;
  return css.slice(0, at) + body + eol + eol + css.slice(at);
}

/** The block currently in `css` (LF), or null. */
export function currentBlock(css) {
  const text = toLf(css);
  const start = text.indexOf('/* motion-tokens:start');
  const end = text.indexOf(END_MARK);
  return start !== -1 && end > start ? text.slice(start, end + END_MARK.length) : null;
}

/** Writes (or with check: true, only compares) both outputs. Returns { stale, wrote }. */
export function generate({ check = false, tokensPath = TOKENS_PATH, cssPath = CSS_PATH, jsPath = JS_PATH } = {}) {
  const tokens = readTokens(tokensPath);
  const springs = sampleSprings(tokens);
  const lift = samplePressLift(tokens);
  const block = cssBlock(tokens, { springs, lift });
  const js = jsModule(tokens, { springs, lift });
  const stale = [];
  const wrote = [];
  const css = readFileSync(cssPath, 'utf8');
  if (currentBlock(css) !== block) {
    stale.push(path.relative(ROOT, cssPath));
    if (!check) { writeFileSync(cssPath, replaceBlock(css, block)); wrote.push(path.relative(ROOT, cssPath)); }
  }
  const currentJs = existsSync(jsPath) ? toLf(readFileSync(jsPath, 'utf8')) : null;
  if (currentJs !== js) {
    stale.push(path.relative(ROOT, jsPath));
    if (!check) { writeFileSync(jsPath, js); wrote.push(path.relative(ROOT, jsPath)); }
  }
  return { stale, wrote };
}

export function main(argv = []) {
  const check = argv.includes('--check');
  try {
    const { stale, wrote } = generate({ check });
    if (check) {
      if (stale.length) { console.error(`stale: ${stale.join(', ')}; run node scripts/gen-motion-tokens.mjs`); return 1; }
      console.log('motion tokens are up to date');
      return 0;
    }
    console.log(wrote.length ? `wrote ${wrote.join(', ')}` : 'motion tokens already up to date');
    return 0;
  } catch (error) {
    if (error instanceof TokenError) { console.error(`motion-tokens.json is invalid: ${error.message}`); return 2; }
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exit(main(process.argv.slice(2)));
}
